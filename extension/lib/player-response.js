// Pure helpers for reading YouTube's ytInitialPlayerResponse with fallbacks.
// Kept dependency-free so the main-world content script and Node tests share the
// exact same extraction rules.

function isPlainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function tryParseJson(value) {
  if (typeof value !== "string") return null;
  try {
    const parsed = JSON.parse(value);
    return isPlainObject(parsed) ? parsed : null;
  } catch {
    return null;
  }
}

function pickFromYtPlayerConfig(windowLike) {
  const args = windowLike?.ytplayer?.config?.args;
  if (!isPlainObject(args)) return null;

  if (isPlainObject(args.raw_player_response)) {
    return args.raw_player_response;
  }

  const parsed = tryParseJson(args.player_response);
  if (parsed) return parsed;

  return null;
}

export function readPlayerResponse(windowLike) {
  if (!isPlainObject(windowLike) && windowLike !== globalThis) {
    // Allow either "a bag of properties" for testing or a real window reference.
    if (typeof windowLike !== "object" || windowLike === null) {
      return null;
    }
  }

  const initial = windowLike?.ytInitialPlayerResponse;
  if (isPlainObject(initial)) {
    return initial;
  }

  const fromConfig = pickFromYtPlayerConfig(windowLike);
  if (fromConfig) {
    return fromConfig;
  }

  // Newer YouTube UIs occasionally expose player data on the ytd-watch-flexy element.
  try {
    const flexy = windowLike?.document?.querySelector?.("ytd-watch-flexy");
    const flexyResponse =
      flexy?.playerData?.playerResponse ?? flexy?.__data?.playerData?.playerResponse;
    if (isPlainObject(flexyResponse)) {
      return flexyResponse;
    }
  } catch {
    // querySelector can throw in non-DOM environments; ignore and keep walking.
  }

  return null;
}

export function hasUsableCaptionTracks(playerResponse) {
  if (!isPlainObject(playerResponse)) return false;
  const tracks = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
  return Array.isArray(tracks) && tracks.length > 0;
}

function languageMatches(track, languageCode) {
  if (!languageCode) return false;
  return new RegExp(`^${languageCode}(?:-|$)`, "i").test(track?.languageCode ?? "");
}

function labelFromName(name, fallback) {
  if (!name) return fallback;
  if (typeof name.simpleText === "string" && name.simpleText.trim()) {
    return name.simpleText.trim();
  }
  if (Array.isArray(name.runs)) {
    const merged = name.runs
      .map((item) => item?.text ?? "")
      .join("")
      .trim();
    if (merged) return merged;
  }
  return fallback;
}

export function summarizeTracks(playerResponse) {
  const empty = { video: { videoId: "", title: "", thumbnailUrl: "" }, tracks: [] };
  if (!isPlainObject(playerResponse)) return empty;

  const videoDetails = isPlainObject(playerResponse.videoDetails)
    ? playerResponse.videoDetails
    : {};
  const thumbnails = Array.isArray(videoDetails?.thumbnail?.thumbnails)
    ? videoDetails.thumbnail.thumbnails
    : [];
  const thumbnailUrl =
    [...thumbnails].reverse().find((entry) => typeof entry?.url === "string" && entry.url)?.url ??
    "";

  const rawTracks = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
  const tracks = Array.isArray(rawTracks)
    ? rawTracks.map((track, index) => ({
        trackIndex: index,
        languageCode: typeof track?.languageCode === "string" ? track.languageCode : "",
        label: labelFromName(track?.name, track?.languageCode ?? `Track ${index + 1}`),
        isAutoGenerated: track?.kind === "asr",
      }))
    : [];

  return {
    video: {
      videoId: typeof videoDetails.videoId === "string" ? videoDetails.videoId : "",
      title: typeof videoDetails.title === "string" ? videoDetails.title : "",
      thumbnailUrl,
    },
    tracks,
  };
}

function safeFilenamePart(value, fallback) {
  if (typeof value !== "string") return fallback;
  const cleaned = value
    .replace(/[^\w.-]+/g, "")
    .replace(/^[.\-]+/, "")
    .replace(/[.\-]+$/, "");
  return cleaned || fallback;
}

function readRowData(row) {
  if (!row || typeof row !== "object") return null;
  return row.data ?? row.__data?.data ?? row.__data ?? row._data ?? null;
}

function toFiniteNumber(value) {
  if (value == null) return null;
  const n = typeof value === "number" ? value : Number.parseInt(String(value), 10);
  return Number.isFinite(n) ? n : null;
}

function readTargetIdFromRow(row) {
  const fromAttribute =
    typeof row?.getAttribute === "function" ? row.getAttribute("target-id") : null;
  if (typeof fromAttribute === "string" && fromAttribute) return fromAttribute;

  const data = readRowData(row);
  if (!data) return null;
  const nested = data.transcriptSegmentRenderer;
  const targetId = data.targetId ?? nested?.targetId;
  return typeof targetId === "string" && targetId ? targetId : null;
}

function readTargetIdTiming(row) {
  const targetId = readTargetIdFromRow(row);
  if (!targetId) return null;

  const numbers = targetId
    .match(/\d+/g)
    ?.map((value) => Number.parseInt(value, 10))
    .filter(Number.isFinite);

  if (!numbers || numbers.length < 2) return null;
  const startMs = numbers[numbers.length - 2];
  const endMs = numbers[numbers.length - 1];
  if (endMs <= startMs) return null;
  return { startMs, endMs };
}

/**
 * Reads millisecond-precision start time from a YouTube transcript segment
 * renderer. YouTube's Polymer element stores precise ms values (not rounded
 * to seconds like the displayed `1:23` timestamp), so preferring this path
 * avoids the "off by 0.x seconds" shadowing drift.
 */
export function readStartMsFromRow(row) {
  const data = readRowData(row);
  if (data) {
    const nested = data.transcriptSegmentRenderer;
    const candidates = [
      data.startMs,
      nested?.startMs,
      data.cueGroupStartOffsetMs,
      nested?.cueGroupStartOffsetMs,
    ];
    for (const value of candidates) {
      const ms = toFiniteNumber(value);
      if (ms !== null) return ms;
    }
  }
  return readTargetIdTiming(row)?.startMs ?? null;
}

/**
 * Reads millisecond-precision end time. Falls back to startMs + durationMs
 * when the element only exposes a duration.
 */
export function readEndMsFromRow(row) {
  const data = readRowData(row);
  if (data) {
    const nested = data.transcriptSegmentRenderer;
    const directEnd = toFiniteNumber(data.endMs ?? nested?.endMs);
    if (directEnd !== null) return directEnd;

    const startMs = toFiniteNumber(data.startMs ?? nested?.startMs);
    const durationMs = toFiniteNumber(data.durationMs ?? nested?.durationMs);
    if (startMs !== null && durationMs !== null) {
      return startMs + durationMs;
    }
  }
  return readTargetIdTiming(row)?.endMs ?? null;
}

export function parseTimestampToMs(value) {
  if (typeof value !== "string") return NaN;
  const trimmed = value.trim();
  if (!trimmed) return NaN;

  const parts = trimmed.split(":");
  if (parts.length < 2 || parts.length > 3) return NaN;

  const numbers = parts.map((part) => Number.parseInt(part, 10));
  if (numbers.some((n) => !Number.isFinite(n))) return NaN;

  if (numbers.length === 2) {
    const [m, s] = numbers;
    return (m * 60 + s) * 1000;
  }
  const [h, m, s] = numbers;
  return (h * 3600 + m * 60 + s) * 1000;
}

// ---------------------------------------------------------------------------
// Transcript DOM helpers.
//
// YouTube renders the transcript panel in two shapes that coexist across builds:
//   legacy <ytd-transcript-segment-renderer> with .segment-timestamp/.segment-text
//   modern <transcript-segment-view-model> with .ytwTranscriptSegmentViewModelTimestamp
//          and .ytAttributedStringHost
// Everything below is selector/row based so it can be unit tested against plain
// row-like objects (only querySelector/childNodes are required).
// ---------------------------------------------------------------------------

export const TRANSCRIPT_ROW_SELECTOR =
  "ytd-transcript-segment-renderer, transcript-segment-view-model";

export const TRANSCRIPT_TEXT_SELECTORS = [
  ".segment-text",
  ".ytAttributedStringHost",
  '[class*="segment-text"]',
  '[class*="SegmentText"]',
  "yt-formatted-string.segment-text",
];

export const TRANSCRIPT_TIMESTAMP_SELECTORS = [
  ".segment-timestamp",
  ".ytwTranscriptSegmentViewModelTimestamp",
  '[class*="segment-timestamp"]',
  '[class*="SegmentTimestamp"]',
];

// Spoken-time accessibility labels ("1 minute, 23 seconds") are announced by
// screen readers next to the visual timestamps. They must never leak into the
// transcript text or be mistaken for a timestamp.
const A11Y_TEXT_NOISE_PATTERN = /a11y|visually-hidden|screen-reader|sr-only/i;
const TRANSCRIPT_TIMESTAMP_PATTERN = /\d{1,3}(?::\d{2}){1,2}/;
const TRANSCRIPT_MIN_OVERFLOW_PX = 8;

export function normalizeTranscriptText(value) {
  if (typeof value !== "string") return "";
  return value
    .replace(/\u00a0/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function hasA11yNoiseClass(element) {
  if (!element || typeof element !== "object" || element.nodeType === 3) return false;

  const className =
    typeof element.className === "string"
      ? element.className
      : (element.getAttribute?.("class") ?? "");
  return A11Y_TEXT_NOISE_PATTERN.test(className);
}

function isA11yNoiseElement(element) {
  if (hasA11yNoiseClass(element)) return true;
  if (!element || typeof element !== "object" || element.nodeType === 3) return false;
  return element.getAttribute?.("aria-hidden") === "true";
}

function readElementVisibleText(element) {
  if (!element || typeof element !== "object") return "";

  const childNodes = Array.isArray(element.childNodes) ? element.childNodes : null;
  if (childNodes && childNodes.length > 0) {
    let text = "";
    const visit = (node) => {
      if (!node || typeof node !== "object") return;
      if (node.nodeType === 3) {
        text += node.nodeValue ?? "";
        return;
      }
      if (isA11yNoiseElement(node)) return;
      const children = Array.isArray(node.childNodes) ? node.childNodes : [];
      for (const child of children) visit(child);
    };
    for (const child of childNodes) visit(child);
    return text;
  }

  return typeof element.textContent === "string" ? element.textContent : "";
}

export function readTranscriptTextFromRow(row) {
  if (!row || typeof row !== "object") return "";

  for (const selector of TRANSCRIPT_TEXT_SELECTORS) {
    let element = null;
    try {
      element = row.querySelector?.(selector) ?? null;
    } catch {
      element = null;
    }
    if (!element || hasA11yNoiseClass(element)) continue;

    const text = normalizeTranscriptText(readElementVisibleText(element));
    if (text) return text;
  }

  return "";
}

export function parseTranscriptTimestamp(text) {
  if (typeof text !== "string") return null;
  const trimmed = text.trim();
  if (!trimmed) return null;

  const parts = trimmed.split(":");
  if (parts.length < 2 || parts.length > 3) return null;

  const numbers = parts.map((part) => Number.parseInt(part, 10));
  if (numbers.some((n) => !Number.isFinite(n))) return null;

  if (numbers.length === 2) {
    const [minutes, seconds] = numbers;
    return (minutes * 60 + seconds) * 1_000;
  }
  const [hours, minutes, seconds] = numbers;
  return (hours * 3600 + minutes * 60 + seconds) * 1_000;
}

export function extractTranscriptTimestamp(text) {
  if (typeof text !== "string") return null;
  const match = text.match(TRANSCRIPT_TIMESTAMP_PATTERN);
  if (!match) return null;
  return parseTranscriptTimestamp(match[0]);
}

/**
 * Resolves a transcript row's timing without touching the network.
 * Resolution order (mirrors the popup's precision accounting):
 *   1. "polymer-ms" — YouTube's internal data object (ms precision)
 *   2. "data-attr"  — data-start-ms DOM attribute (ms precision)
 *   3. "text"       — parsed from the displayed M:SS/H:MM:SS label (second precision)
 */
export function resolveTranscriptRowTiming(row) {
  if (!row || typeof row !== "object") return null;

  const startMs = readStartMsFromRow(row);
  if (startMs !== null) {
    return { startMs, endMs: readEndMsFromRow(row), precision: "polymer-ms" };
  }

  const segmentLike = row.querySelector?.(".segment") ?? row;
  const attributeValue =
    segmentLike?.getAttribute?.("data-start-ms") ?? row.getAttribute?.("data-start-ms") ?? null;
  if (attributeValue != null) {
    const fromAttribute = toFiniteNumber(attributeValue);
    if (fromAttribute !== null) {
      return { startMs: fromAttribute, endMs: null, precision: "data-attr" };
    }
  }

  for (const selector of TRANSCRIPT_TIMESTAMP_SELECTORS) {
    let element = null;
    try {
      element = row.querySelector?.(selector) ?? null;
    } catch {
      element = null;
    }
    if (!element) continue;

    const label = readElementVisibleText(element) || element.textContent || "";
    const fromText = extractTranscriptTimestamp(label);
    if (fromText !== null) {
      return { startMs: fromText, endMs: null, precision: "text" };
    }
  }

  return null;
}

function normalizeTranscriptSegment(segment) {
  if (!segment || typeof segment !== "object") return null;

  const startMs = toFiniteNumber(segment.startMs);
  if (startMs === null) return null;

  const text = normalizeTranscriptText(segment.text);
  if (!text) return null;

  const rawEndMs = toFiniteNumber(segment.endMs);
  const endMs = rawEndMs !== null && rawEndMs > startMs ? rawEndMs : null;
  return { startMs, endMs, text };
}

/**
 * Dedupes rows re-rendered across scroll passes. Keyed by startMs + normalized
 * text, so the same row rendered twice collapses; when a duplicate carries a
 * longer known end time, that end time wins.
 */
export function dedupeTranscriptSegments(segments) {
  const byKey = new Map();

  for (const segment of Array.isArray(segments) ? segments : []) {
    const normalized = normalizeTranscriptSegment(segment);
    if (!normalized) continue;

    const key = `${normalized.startMs}|${normalized.text}`;
    const prior = byKey.get(key);
    if (!prior) {
      byKey.set(key, normalized);
      continue;
    }
    if (prior.endMs === null || (normalized.endMs !== null && normalized.endMs > prior.endMs)) {
      byKey.set(key, { ...prior, endMs: normalized.endMs });
    }
  }

  return Array.from(byKey.values()).sort(
    (a, b) => a.startMs - b.startMs || a.text.localeCompare(b.text),
  );
}

/**
 * Sorts by start time and fills missing/invalid end times from the next
 * segment's start. The final segment gets `lastPaddingMs` of breathing room.
 */
export function fillTranscriptEndMs(segments, options = {}) {
  const lastPaddingMs = toFiniteNumber(options.lastPaddingMs) ?? 3_000;
  const minDurationMs = toFiniteNumber(options.minDurationMs) ?? 200;

  const normalized = (Array.isArray(segments) ? segments : [])
    .map((segment) => normalizeTranscriptSegment(segment))
    .filter(Boolean)
    .sort((a, b) => a.startMs - b.startMs);

  return normalized.map((segment, index) => {
    const next = normalized[index + 1];
    const explicitEnd = segment.endMs;
    const endMs =
      explicitEnd !== null
        ? explicitEnd
        : next
          ? Math.max(next.startMs, segment.startMs + minDurationMs)
          : segment.startMs + lastPaddingMs;
    return { startMs: segment.startMs, endMs, text: segment.text };
  });
}

/**
 * Merges transcript rows collected across one or more scroll passes (plus any
 * rows collected before scrolling) into a deduped, sorted, end-filled list.
 */
export function mergeTranscriptRows(batches, existing = []) {
  const rows = [];
  const append = (value) => {
    if (Array.isArray(value)) rows.push(...value);
    else if (value) rows.push(value);
  };

  for (const batch of Array.isArray(batches) ? batches : [batches]) append(batch);
  append(existing);

  return fillTranscriptEndMs(dedupeTranscriptSegments(rows));
}

/**
 * Decides whether the transcript list actually overflows its viewport, so a
 * single read pass is enough for short videos.
 */
export function shouldScrollTranscript(metrics, options = {}) {
  if (!metrics || typeof metrics !== "object") return false;

  const scrollHeight = Number(metrics.scrollHeight);
  const clientHeight = Number(metrics.clientHeight);
  if (!Number.isFinite(scrollHeight) || !Number.isFinite(clientHeight)) return false;
  if (scrollHeight <= 0 || clientHeight <= 0) return false;

  const minOverflowPx = toFiniteNumber(options.minOverflowPx) ?? TRANSCRIPT_MIN_OVERFLOW_PX;
  return scrollHeight - clientHeight > minOverflowPx;
}

// ---------------------------------------------------------------------------
// Transcript scroll completeness.
//
// YouTube virtualizes long transcript lists: only the rows near the viewport
// exist in the DOM at any moment. Collecting the whole transcript therefore
// needs a deterministic top-to-bottom sweep of the scroll container. The sweep
// below is pure and dependency-injected (snapshot/scroll/merge/sleep/clock) so
// Node tests can simulate a virtualized list exactly and the MAIN-world script
// can drive it against the real DOM.
//
// Contract: `complete: false` means "this is NOT the whole transcript"; callers
// MUST surface an error with the returned diagnostics instead of importing the
// partial rows.
// ---------------------------------------------------------------------------

export const TRANSCRIPT_SCROLL_STEP_DELAY_MS = 60;
export const TRANSCRIPT_SCROLL_OVERLAP_PX = 40;
export const TRANSCRIPT_SCROLL_IDLE_PASSES = 2;
export const TRANSCRIPT_SCROLL_MAX_STEPS = 400;
export const TRANSCRIPT_SCROLL_ABSOLUTE_MAX_STEPS = 2_000;
export const TRANSCRIPT_SCROLL_MIN_STEP_PX = 60;
export const TRANSCRIPT_SCROLL_BOTTOM_EPSILON_PX = 2;
export const TRANSCRIPT_SCROLL_BUDGET_MIN_MS = 15_000;
export const TRANSCRIPT_SCROLL_BUDGET_MAX_MS = 90_000;
export const TRANSCRIPT_SCROLL_BUDGET_OVERHEAD_MS = 2_000;
export const TRANSCRIPT_SCROLL_BUDGET_SAFETY_FACTOR = 1.5;
// A fully rendered list reports renderedCount >= the scrollHeight/rowStride
// estimate (minus at most one row for ceil rounding). The MAIN-world reader
// derives that estimate from the *smallest* sampled row height, so the estimate
// errs high and the shortcut can never under-count rows.
const TRANSCRIPT_FULLY_RENDERED_TOLERANCE_ROWS = 1;

function readSnapshotObject(snapshot) {
  return snapshot && typeof snapshot === "object" ? snapshot : {};
}

function readSnapshotRows(snapshot) {
  return Array.isArray(snapshot?.rows) ? snapshot.rows : [];
}

function readSnapshotNumber(snapshot, key) {
  const value = Number(snapshot?.[key]);
  return Number.isFinite(value) ? value : 0;
}

function isTranscriptAtBottom(snapshot) {
  const scrollHeight = readSnapshotNumber(snapshot, "scrollHeight");
  const clientHeight = readSnapshotNumber(snapshot, "clientHeight");
  const scrollTop = readSnapshotNumber(snapshot, "scrollTop");
  const maxScrollTop = Math.max(0, scrollHeight - clientHeight);
  return scrollTop >= maxScrollTop - TRANSCRIPT_SCROLL_BOTTOM_EPSILON_PX;
}

function isTranscriptFullyRendered(snapshot) {
  const renderedCount = Number(snapshot?.renderedCount);
  const estimatedTotalRows = Number(snapshot?.estimatedTotalRows);
  if (!Number.isFinite(renderedCount) || !Number.isFinite(estimatedTotalRows)) return false;
  if (estimatedTotalRows <= 0) return false;
  return renderedCount >= estimatedTotalRows - TRANSCRIPT_FULLY_RENDERED_TOLERANCE_ROWS;
}

/**
 * Estimated number of viewport-sized scroll steps needed to sweep the list from
 * top to bottom. 0 when the list does not really overflow.
 */
export function estimateTranscriptScrollSteps(metrics, options = {}) {
  if (!metrics || typeof metrics !== "object") return 0;
  if (!shouldScrollTranscript(metrics)) return 0;

  const scrollHeight = Number(metrics.scrollHeight);
  const clientHeight = Number(metrics.clientHeight);
  if (!Number.isFinite(scrollHeight) || !Number.isFinite(clientHeight)) return 0;

  const overlapPx = Math.max(0, toFiniteNumber(options.overlapPx) ?? TRANSCRIPT_SCROLL_OVERLAP_PX);
  const viewportStep = Math.max(clientHeight - overlapPx, TRANSCRIPT_SCROLL_MIN_STEP_PX);
  const maxScrollTop = Math.max(0, scrollHeight - clientHeight);
  return Math.ceil(maxScrollTop / viewportStep);
}

/**
 * Adaptive completeness budget: one full sweep at the configured step delay plus
 * safety margin, clamped to [15s, 90s]. Deliberately not a fixed 10s constant —
 * long transcripts need proportionally more time, and the caller turns an
 * exhausted budget into an explicit error rather than a truncated transcript.
 */
export function computeTranscriptScrollBudgetMs(options = {}) {
  const scrollHeight = Number(options.scrollHeight);
  const clientHeight = Number(options.clientHeight);
  const steps = estimateTranscriptScrollSteps(
    { scrollHeight, clientHeight },
    { overlapPx: options.overlapPx },
  );
  const stepDelayMs = Math.max(
    0,
    toFiniteNumber(options.stepDelayMs) ?? TRANSCRIPT_SCROLL_STEP_DELAY_MS,
  );
  const minBudgetMs = toFiniteNumber(options.minBudgetMs) ?? TRANSCRIPT_SCROLL_BUDGET_MIN_MS;
  const maxBudgetMs = toFiniteNumber(options.maxBudgetMs) ?? TRANSCRIPT_SCROLL_BUDGET_MAX_MS;
  const overheadMs = toFiniteNumber(options.overheadMs) ?? TRANSCRIPT_SCROLL_BUDGET_OVERHEAD_MS;

  const rawBudgetMs =
    steps * stepDelayMs * TRANSCRIPT_SCROLL_BUDGET_SAFETY_FACTOR + Math.max(0, overheadMs);
  return Math.min(Math.max(rawBudgetMs, minBudgetMs), maxBudgetMs);
}

/**
 * Sweeps a (possibly virtualized) transcript scroll container and reports
 * whether the collected rows are the whole transcript.
 *
 * Required options:
 *   readSnapshot(): { rows, scrollTop, scrollHeight, clientHeight, renderedCount,
 *                     estimatedTotalRows? }
 *   setScrollTop(scrollTop): applies a scroll position to the container.
 * Optional options:
 *   mergeRows(accumulatedRows, batch) -> accumulatedRows (defaults to concat)
 *   sleep(ms), now(), budgetMs, stepDelayMs, maxSteps, overlapPx, idlePasses
 *
 * Guarantees:
 *   - no real overflow -> one pass, complete (reason "no_overflow")
 *   - DOM already holds every row -> no scrolling at all (reason "fully_rendered")
 *   - overflow sweep advances at most `clientHeight - overlapPx` per step; rows
 *     are never skipped for the sake of speed (no acceleration multiplier)
 *   - complete only after reaching the bottom AND `idlePasses` consecutive
 *     passes with no new rows
 *   - incomplete with reason "budget" | "step_cap" | "stalled" when limits hit;
 *     `atBottom` stays false unless the bottom was actually reached
 *   - a container that exposes rows but has no measurable viewport (hidden or
 *     collapsed panel) is reported incomplete (reason "stalled") — never treated
 *     as "no overflow" — because completeness cannot be proven without a viewport
 *   - the caller's original scrollTop is restored before returning
 */
export async function collectTranscriptRowsByScroll(options = {}) {
  const readSnapshot = options.readSnapshot;
  const setScrollTop = options.setScrollTop;
  if (typeof readSnapshot !== "function") {
    throw new TypeError("collectTranscriptRowsByScroll requires a readSnapshot() function.");
  }
  if (typeof setScrollTop !== "function") {
    throw new TypeError("collectTranscriptRowsByScroll requires a setScrollTop() function.");
  }

  const mergeRows =
    typeof options.mergeRows === "function"
      ? options.mergeRows
      : (rows, batch) =>
          (Array.isArray(rows) ? rows : []).concat(Array.isArray(batch) ? batch : []);
  const sleep =
    typeof options.sleep === "function"
      ? options.sleep
      : (ms) => new Promise((resolve) => setTimeout(resolve, Math.max(0, ms)));
  const now = typeof options.now === "function" ? options.now : () => Date.now();

  const budgetMs = Math.max(0, toFiniteNumber(options.budgetMs) ?? TRANSCRIPT_SCROLL_BUDGET_MIN_MS);
  const stepDelayMs = Math.max(
    0,
    toFiniteNumber(options.stepDelayMs) ?? TRANSCRIPT_SCROLL_STEP_DELAY_MS,
  );
  const maxSteps = Math.max(
    1,
    Math.floor(toFiniteNumber(options.maxSteps) ?? TRANSCRIPT_SCROLL_MAX_STEPS),
  );
  const overlapPx = Math.max(0, toFiniteNumber(options.overlapPx) ?? TRANSCRIPT_SCROLL_OVERLAP_PX);
  const idlePasses = Math.max(
    1,
    Math.floor(toFiniteNumber(options.idlePasses) ?? TRANSCRIPT_SCROLL_IDLE_PASSES),
  );

  const startedAt = now();
  const elapsedMs = () => Math.max(0, now() - startedAt);

  const applyMerge = (currentRows, batch) => {
    const merged = mergeRows(currentRows, readSnapshotRows(batch));
    return Array.isArray(merged) ? merged : currentRows;
  };

  let snapshot = readSnapshotObject(readSnapshot());
  let rows = applyMerge([], snapshot);
  const originalScrollTop = readSnapshotNumber(snapshot, "scrollTop");
  let steps = 0;
  let atBottom = isTranscriptAtBottom(snapshot);

  // A container that still exposes rows but has no measurable viewport (hidden
  // or collapsed panel) cannot be swept, so completeness cannot be proven there.
  if (rows.length > 0 && readSnapshotNumber(snapshot, "clientHeight") <= 0) {
    return {
      rows,
      complete: false,
      reason: "stalled",
      steps,
      elapsedMs: elapsedMs(),
      atBottom: false,
    };
  }

  // Short/non-overflowing lists are complete after the single pass above.
  if (!shouldScrollTranscript(snapshot)) {
    return {
      rows,
      complete: true,
      reason: "no_overflow",
      steps,
      elapsedMs: elapsedMs(),
      atBottom,
    };
  }

  // Fully rendered (non-virtualized) lists already hold every row in the DOM —
  // scrolling would only burn time, so skip the sweep entirely.
  if (isTranscriptFullyRendered(snapshot)) {
    return {
      rows,
      complete: true,
      reason: "fully_rendered",
      steps,
      elapsedMs: elapsedMs(),
      atBottom,
    };
  }

  let complete = false;
  let reason = null;

  try {
    // Deterministic top-down sweep: start at the very top so early rows are seen
    // even when the viewer had the panel scrolled down.
    setScrollTop(0);
    await sleep(stepDelayMs);

    snapshot = readSnapshotObject(readSnapshot());
    rows = applyMerge(rows, snapshot);
    let top = readSnapshotNumber(snapshot, "scrollTop");
    let idle = 0;

    while (true) {
      const clientHeight = readSnapshotNumber(snapshot, "clientHeight");
      const maxScrollTop = Math.max(0, readSnapshotNumber(snapshot, "scrollHeight") - clientHeight);
      const viewportStep = Math.max(clientHeight - overlapPx, TRANSCRIPT_SCROLL_MIN_STEP_PX);
      const atBottomNow = top >= maxScrollTop - TRANSCRIPT_SCROLL_BOTTOM_EPSILON_PX;

      if (atBottomNow && idle >= idlePasses) {
        complete = true;
        break;
      }
      if (steps >= maxSteps) {
        reason = "step_cap";
        break;
      }
      if (elapsedMs() > budgetMs) {
        reason = "budget";
        break;
      }

      const nextTop = Math.min(top + viewportStep, maxScrollTop);
      if (nextTop > top) {
        setScrollTop(nextTop);
      }
      await sleep(stepDelayMs);

      const rowsBefore = rows.length;
      snapshot = readSnapshotObject(readSnapshot());
      rows = applyMerge(rows, snapshot);

      const added = Math.max(0, rows.length - rowsBefore);
      steps += 1;

      const settledTop = readSnapshotNumber(snapshot, "scrollTop");
      const maxScrollTopAfter = Math.max(
        0,
        readSnapshotNumber(snapshot, "scrollHeight") - readSnapshotNumber(snapshot, "clientHeight"),
      );
      const atBottomAfter = settledTop >= maxScrollTopAfter - TRANSCRIPT_SCROLL_BOTTOM_EPSILON_PX;

      idle = added === 0 ? idle + 1 : 0;

      if (atBottomAfter) {
        atBottom = true;
        if (idle >= idlePasses) {
          complete = true;
          break;
        }
      } else if (added === 0 && settledTop <= top) {
        // The container refused to move and nothing new rendered: another pass
        // cannot reveal rows, and we never reached the bottom.
        reason = "stalled";
        break;
      }

      top = settledTop;
    }
  } finally {
    // Restore the viewer's scroll position; collected rows stay with the caller.
    try {
      setScrollTop(originalScrollTop);
    } catch {
      // Best-effort restoration only.
    }
  }

  return { rows, complete, reason, steps, elapsedMs: elapsedMs(), atBottom };
}

function readControlTextCandidates(control) {
  if (!control || typeof control !== "object") return [];

  const candidates = [];
  const getAttribute =
    typeof control.getAttribute === "function" ? control.getAttribute.bind(control) : null;

  for (const attr of ["aria-label", "title"]) {
    const value = getAttribute?.(attr);
    if (typeof value === "string" && value.trim()) candidates.push(value);
  }

  if (typeof control.textContent === "string" && control.textContent.trim()) {
    candidates.push(control.textContent);
  }

  return candidates;
}

function normalizeControlText(value) {
  return String(value)
    .replace(/\u00a0/g, " ")
    .replace(/…/g, "...")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

function controlMatches(control, patterns, excludePatterns = []) {
  const labels = readControlTextCandidates(control).map(normalizeControlText);
  if (labels.some((label) => excludePatterns.some((pattern) => pattern.test(label)))) {
    return false;
  }
  return labels.some((label) => patterns.some((pattern) => pattern.test(label)));
}

const TRANSCRIPT_CONTROL_PATTERNS = [
  /\bshow transcript\b/i,
  /\bopen transcript\b/i,
  /\btranscript\b/i,
  /字幕/i,
  /文字稿/i,
  /转录/i,
];

const DESCRIPTION_EXPAND_PATTERNS = [
  /^more$/i,
  /^\.\.\.more$/i,
  /^show more$/i,
  /^read more$/i,
  /^更多$/i,
  /^显示更多$/i,
  /^展开$/i,
];

const DESCRIPTION_EXPAND_EXCLUDES = [/\bmore actions\b/i, /\bmore options\b/i, /\blearn more\b/i];

export function isTranscriptOpenControl(control) {
  return controlMatches(control, TRANSCRIPT_CONTROL_PATTERNS);
}

export function isDescriptionExpandControl(control) {
  return controlMatches(control, DESCRIPTION_EXPAND_PATTERNS, DESCRIPTION_EXPAND_EXCLUDES);
}

export function buildDownloadFilename({ videoId, languageCode, isAutoGenerated }) {
  const safeVideo = safeFilenamePart(videoId, "unknown");
  const safeLang = safeFilenamePart(languageCode, "unknown");
  const suffix = isAutoGenerated ? "-auto" : "";
  return `shadowing-${safeVideo}-${safeLang}${suffix}.json`;
}

export function chooseCaptionTrack(tracks, options = {}) {
  if (!Array.isArray(tracks) || tracks.length === 0) {
    return null;
  }

  const preferredLanguage = options.preferredLanguage ?? "en";

  const manualPreferred = tracks.find(
    (track) => languageMatches(track, preferredLanguage) && track?.kind !== "asr",
  );
  if (manualPreferred) return manualPreferred;

  const anyPreferred = tracks.find((track) => languageMatches(track, preferredLanguage));
  if (anyPreferred) return anyPreferred;

  const manualFallback = tracks.find((track) => track?.kind !== "asr");
  if (manualFallback) return manualFallback;

  return tracks[0] ?? null;
}
